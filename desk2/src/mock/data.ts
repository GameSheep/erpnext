import type { FrappeDoc } from '@/types/frappe';

const now = new Date();
function daysAgo(n: number): string {
	const d = new Date(now);
	d.setDate(d.getDate() - n);
	return d.toISOString().slice(0, 10);
}
function daysAhead(n: number): string {
	return daysAgo(-n);
}

